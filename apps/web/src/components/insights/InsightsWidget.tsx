'use client';

import { useState, useEffect } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import { useInsights } from '@/hooks/useInsights';
import { InsightCard } from './InsightCard';
import { InsightsPanel } from './InsightsPanel';
import {
  SparklesIcon,
  ChevronRightIcon,
  ArrowPathIcon,
} from '@heroicons/react/24/outline';

interface InsightsWidgetProps {
  /** Number of insights to show */
  showCount?: number;
  /** Auto-generate insights on mount if none exist */
  autoGenerate?: boolean;
  /** Compact mode for sidebar */
  compact?: boolean;
}

/**
 * Insights Widget
 * 
 * Compact display of personalized insights for the dashboard.
 */
export function InsightsWidget({ 
  showCount = 3, 
  autoGenerate = true,
  compact = false,
}: InsightsWidgetProps) {
  const { 
    insights, 
    activeCount, 
    isLoading, 
    isGenerating,
    generateInsights,
    dismissInsight,
    highPriorityInsights,
  } = useInsights();
  
  const [isPanelOpen, setIsPanelOpen] = useState(false);
  const [hasAutoGenerated, setHasAutoGenerated] = useState(false);

  // Auto-generate insights on first load if none exist
  useEffect(() => {
    if (autoGenerate && !isLoading && insights.length === 0 && !hasAutoGenerated && !isGenerating) {
      setHasAutoGenerated(true);
      generateInsights();
    }
  }, [autoGenerate, isLoading, insights.length, hasAutoGenerated, isGenerating, generateInsights]);

  // Display insights - prioritize high priority, then most relevant
  const displayInsights = highPriorityInsights.length > 0 
    ? highPriorityInsights.slice(0, showCount)
    : insights.slice(0, showCount);

  if (compact) {
    return (
      <>
        <button
          onClick={() => setIsPanelOpen(true)}
          className="flex items-center gap-2 px-3 py-1.5 rounded-lg bg-white/5 hover:bg-white/10 transition-colors group"
        >
          <SparklesIcon className="w-4 h-4 text-purple-400" />
          <span className="text-sm font-medium text-white/70 group-hover:text-white">
            Insights
          </span>
          {activeCount > 0 && (
            <span className="px-1.5 py-0.5 text-xs font-medium bg-purple-500/20 text-purple-400 rounded">
              {activeCount}
            </span>
          )}
        </button>

        <InsightsPanel isOpen={isPanelOpen} onClose={() => setIsPanelOpen(false)} />
      </>
    );
  }

  return (
    <>
      <motion.div
        initial={{ opacity: 0, y: 10 }}
        animate={{ opacity: 1, y: 0 }}
        className="p-4 rounded-xl bg-white/[0.02] border border-white/10"
      >
        {/* Header */}
        <div className="flex items-center justify-between mb-4">
          <div className="flex items-center gap-2">
            <SparklesIcon className="w-5 h-5 text-purple-400" />
            <h3 className="font-semibold text-white">Insights</h3>
            {activeCount > 0 && (
              <span className="px-2 py-0.5 text-xs font-medium bg-purple-500/20 text-purple-400 rounded-full">
                {activeCount}
              </span>
            )}
          </div>
          <div className="flex items-center gap-2">
            <button
              onClick={generateInsights}
              disabled={isGenerating}
              className="p-2 rounded-lg text-white/40 hover:text-white hover:bg-white/5 transition-colors disabled:opacity-50"
              title="Refresh insights"
            >
              <ArrowPathIcon className={`w-4 h-4 ${isGenerating ? 'animate-spin' : ''}`} />
            </button>
            <button
              onClick={() => setIsPanelOpen(true)}
              className="flex items-center gap-1 text-xs text-white/50 hover:text-white transition-colors"
            >
              View All
              <ChevronRightIcon className="w-3 h-3" />
            </button>
          </div>
        </div>

        {/* Content */}
        {isLoading || isGenerating ? (
          <div className="flex items-center justify-center py-8">
            <div className="w-6 h-6 border-2 border-purple-400 border-t-transparent rounded-full animate-spin" />
            {isGenerating && (
              <span className="ml-3 text-sm text-white/40">Analyzing your trades...</span>
            )}
          </div>
        ) : displayInsights.length > 0 ? (
          <div className="space-y-2">
            <AnimatePresence mode="popLayout">
              {displayInsights.map(insight => (
                <InsightCard
                  key={insight.id}
                  insight={insight}
                  onDismiss={() => dismissInsight(insight.id)}
                  compact
                />
              ))}
            </AnimatePresence>
          </div>
        ) : (
          <div className="text-center py-6">
            <SparklesIcon className="w-10 h-10 text-white/10 mx-auto mb-2" />
            <p className="text-sm text-white/40">
              Log more trades to unlock insights
            </p>
            <p className="text-xs text-white/30 mt-1">
              Need at least 5 trades
            </p>
          </div>
        )}
      </motion.div>

      <InsightsPanel isOpen={isPanelOpen} onClose={() => setIsPanelOpen(false)} />
    </>
  );
}
